"""NEON: the Neon Summers logo (assets/neon-summers-logo.png) as a C header for the splash and the DRIVE page.
   gen_logo.py OUT.h
LOGO_N x LOGO_N pixels, 2 bits of coverage each (0 clear .. 3 solid), 4 a byte, rows top to bottom; LOGO_ROW[]: the
logo's own colour per row (RGB565: its magenta-to-orange gradient), what SUNSET draws; other palettes their own."""
import sys
from pathlib import Path
from PIL import Image

N = 96
src = Path(__file__).resolve().parent.parent / "assets" / "neon-summers-logo.png"
im = Image.open(src).convert("RGBA")
bb = im.getchannel("A").getbbox()
im = im.crop(bb)
side = max(im.size)
sq = Image.new("RGBA", (side, side), (0, 0, 0, 0))
sq.paste(im, ((side - im.size[0]) // 2, (side - im.size[1]) // 2))
small = sq.resize((N, N), Image.LANCZOS)
px = small.load()
alpha = [[min(3, (px[x, y][3] * 4) // 256) for x in range(N)] for y in range(N)]
big = sq.resize((N, N * 8), Image.BOX).load()   # (a row's colour from the source's opaque pixels)
rows = []
for y in range(N):
    acc = [0, 0, 0, 0]
    for yy in range(y * 8, y * 8 + 8):
        for x in range(N):
            r, g, b, a = big[x, yy]
            if a > 200:
                acc[0] += r; acc[1] += g; acc[2] += b; acc[3] += 1
    if not acc[3]:
        rows.append(rows[-1] if rows else 0xF81F)
        continue
    r, g, b = (acc[i] // acc[3] for i in range(3))
    rows.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
packed = []
for y in range(N):
    for x in range(0, N, 4):
        packed.append(sum(alpha[y][x + k] << (2 * k) for k in range(4)))
out = ["/* generated by tools/gen_logo.py from assets/neon-summers-logo.png: do not edit */",
       "#define LOGO_N %d" % N,
       "static const uint8_t LOGO_A[%d] = {" % len(packed)]
for i in range(0, len(packed), 24):
    out.append("    " + ", ".join("%d" % v for v in packed[i:i + 24]) + ",")
out.append("};")
out.append("static const uint16_t LOGO_ROW[%d] = {" % N)
for i in range(0, N, 12):
    out.append("    " + ", ".join("0x%04X" % v for v in rows[i:i + 12]) + ",")
out.append("};")
Path(sys.argv[1]).write_text("\n".join(out) + "\n")
print("gen_logo.py: %s, %d x %d, %d B" % (sys.argv[1], N, N, len(packed) + 2 * N))
